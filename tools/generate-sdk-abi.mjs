// Embeds abi/*.json into sdk/abi.mjs so the browser entrypoint needs no fs access.
// `--check` fails when the embedded copy differs from the exported ABI files; it never edits abi/.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const names = ['RelayFactory', 'RelayBranch', 'RelayEncoder', 'RelayVerifier', 'IIntake'];
const entries = [];
for (const name of names) {
  const raw = await readFile(new URL(`abi/${name}.json`, root));
  entries.push({ name, sha256: createHash('sha256').update(raw).digest('hex'), abi: JSON.parse(raw.toString('utf8')) });
}
const source = `// GENERATED by tools/generate-sdk-abi.mjs from abi/*.json. Do not edit by hand.\n`
  + `// Environment-neutral: no fs, Buffer, DNS or network access.\n`
  + `export const ABI_SOURCE_SHA256 = Object.freeze(${JSON.stringify(Object.fromEntries(entries.map(e => [e.name, e.sha256])), null, 2)});\n`
  + `export const ABIS = Object.freeze({\n${entries.map(e => `  ${e.name}: ${JSON.stringify(e.abi)}`).join(',\n')}\n});\n`;
const target = new URL('sdk/abi.mjs', root);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== source) { console.error('sdk/abi.mjs is out of date with abi/*.json'); process.exit(1); }
  console.log(JSON.stringify({ ok: true, abiSha256: Object.fromEntries(entries.map(e => [e.name, e.sha256])) }, null, 2));
} else {
  await writeFile(target, source);
  console.log('wrote sdk/abi.mjs');
}
