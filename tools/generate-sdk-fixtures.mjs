import { readFile, writeFile } from 'node:fs/promises';
import { createProject, witnessHash } from '../sdk/index.mjs';
import { keccak256, toBeHex } from '../vendor/ethers/ethers.mjs';
const root = new URL('../', import.meta.url);
const raw = await readFile(new URL('test/fixtures/document.md.result.json', root));
const parsed = JSON.parse(raw);
const file = parsed.files[0];
const witness = [{
  key: toBeHex(1, 32), kind: 0, name: file.name, path: file.path,
  fileHash: `0x${file.hash}`, mediaType: file.mediaType, size: file.bytes,
  submissionHash: `0x${file.submissionHash}`,
  producer: '0x2000000000000000000000000000000000000002', // Local ABI fixture only.
  jobId: parsed.jobId, resultHash: keccak256(raw), revision: 1
}];
const digest = witnessHash(witness);
const create = createProject('0x1000000000000000000000000000000000000001', 'SDK golden goal');
await writeFile(new URL('test/fixtures/sdk-golden.json', root), JSON.stringify({ witness, digest, createCalldata: create.data }, null, 2) + '\n');
await writeFile(new URL('test/fixtures/SdkGolden.sol', root), `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

// Generated by tools/generate-sdk-fixtures.mjs. Local ABI fixtures, never deployment parameters.
library SdkGolden {
    function digest() internal pure returns (bytes32) { return ${digest}; }
    function createCalldata() internal pure returns (bytes memory) { return hex"${create.data.slice(2)}"; }
}
`);
